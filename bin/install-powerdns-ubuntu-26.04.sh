#!/usr/bin/env bash
# Ubuntu 26.04 installer/resumer. Installs PowerDNS Authoritative 5.1,
# MariaDB 12.3 LTS, a local-only API, and a DNSSEC-capable gmysql backend.
set -Eeuo pipefail
umask 077
export DEBIAN_FRONTEND=noninteractive

die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }
note() { printf '%s\n' "$*" >&2; }
on_error() { note "PowerDNS task stopped at line $1. Check: journalctl -u pdns -u mariadb -n 100"; }
trap 'on_error "$LINENO"' ERR

make_api_hash() {
  # pdnsutil prefers /dev/tty over stdin. setsid removes the controlling tty,
  # making it read exactly the generated key from the pipe.
  command -v setsid >/dev/null || die 'The util-linux setsid command is required.'
  command -v python3 >/dev/null || die 'Python 3 is required to verify the API hash.'
  api_hash=$(printf '%s\n' "$api_key" | setsid -w pdnsutil hash-password)
  [[ $api_hash == '$scrypt$ln='* && $api_hash != *$'\n'* ]] ||
    die 'Could not generate a valid PowerDNS API key hash.'
  if ! PDNS_CHECK_KEY="$api_key" PDNS_CHECK_HASH="$api_hash" python3 - <<'PY'; then
import base64
import hashlib
import hmac
import os

parts = os.environ['PDNS_CHECK_HASH'].split('$')
if len(parts) != 5 or parts[1] != 'scrypt':
    raise SystemExit(1)
params = dict(pair.split('=', 1) for pair in parts[2].split(','))
salt = base64.b64decode(parts[3], validate=True)
expected = base64.b64decode(parts[4], validate=True)
actual = hashlib.scrypt(
    os.environ['PDNS_CHECK_KEY'].encode('ascii'), salt=salt,
    n=1 << int(params['ln']), r=int(params['r']), p=int(params['p']),
    dklen=len(expected),
)
raise SystemExit(0 if hmac.compare_digest(actual, expected) else 1)
PY
    die 'The generated API hash does not match the saved API key.'
  fi
}

verify_server() {
  systemctl is-active --quiet pdns || die 'PowerDNS is not running.'
  cat > "$workdir/curl.conf" <<EOF
header = "X-API-Key: $api_key"
EOF
  curl --silent --show-error --fail --max-time 5 --config "$workdir/curl.conf" \
    http://127.0.0.1:8081/api/v1/servers/localhost > "$workdir/api-response"
  grep -q '"id"' "$workdir/api-response" || die 'PowerDNS API response is invalid.'
  for transport in udp tcp; do
    args=()
    [[ $transport == tcp ]] && args+=(+tcp)
    dig @127.0.0.1 -p 53 +time=2 +tries=1 +norecurse "${args[@]}" \
      pdns-install-check.invalid SOA > "$workdir/dig-$transport"
    grep -q 'status: REFUSED' "$workdir/dig-$transport" ||
      die "PowerDNS did not answer the $transport DNS test as expected."
  done
  note 'PowerDNS service, API, UDP DNS, and TCP DNS checks passed.'
}

[[ ${EUID} -eq 0 ]] || die 'Run as root (sudo bash install-powerdns-ubuntu-26.04.sh).'
[[ -f /etc/os-release ]] || die 'Cannot identify operating system.'
# shellcheck disable=SC1091
source /etc/os-release
[[ ${ID:-} == ubuntu && ${VERSION_ID:-} == 26.04 && ${VERSION_CODENAME:-} == resolute ]] ||
  die 'Only Ubuntu 26.04 (resolute) is supported.'
[[ $(dpkg --print-architecture) == amd64 || $(dpkg --print-architecture) == arm64 ]] ||
  die 'The upstream PowerDNS 5.1 repository requires amd64 or arm64.'
[[ -d /run/systemd/system ]] || die 'systemd must be running.'
[[ $# -eq 0 || ( $# -eq 1 && ( $1 == --verify-only || $1 == --repair-api ) ) ]] ||
  die 'Usage: sudo bash install-powerdns-ubuntu-26.04.sh [--verify-only|--repair-api]'
if [[ ${1:-} == --verify-only || ${1:-} == --repair-api ]]; then
  [[ -f /root/powerdns-credentials ]] || die 'Credentials file is missing.'
  api_key=$(sed -n 's/^PowerDNS API key: //p' /root/powerdns-credentials)
  [[ $api_key =~ ^[[:xdigit:]]{64}$ ]] || die 'Saved API key is invalid.'
  workdir=$(mktemp -d)
  trap 'rm -rf -- "$workdir"' EXIT
  if [[ ${1:-} == --repair-api ]]; then
    [[ -f /etc/powerdns/pdns.conf ]] &&
      grep -q '^# Generated by install-powerdns-ubuntu-26.04.sh$' /etc/powerdns/pdns.conf ||
      die 'PowerDNS configuration is not managed by this installer.'
    make_api_hash
    cp -a /etc/powerdns/pdns.conf "$workdir/pdns.conf.backup"
    awk -v hash="$api_hash" '
      /^api-key=/ {print "api-key=" hash; found=1; next}
      {print}
      END {if (!found) exit 1}
    ' "$workdir/pdns.conf.backup" > "$workdir/pdns.conf" || die 'Could not update API key setting.'
    install -o root -g pdns -m 0640 "$workdir/pdns.conf" /etc/powerdns/pdns.conf
    if ! systemctl restart pdns; then
      install -o root -g pdns -m 0640 "$workdir/pdns.conf.backup" /etc/powerdns/pdns.conf
      systemctl restart pdns || true
      die 'PowerDNS rejected the repaired configuration; the previous file was restored.'
    fi
  fi
  verify_server
  exit 0
fi
if ! command -v ss >/dev/null; then
  note 'Installing iproute2 for the port conflict check...'
  apt-get update
  apt-get install -y --no-install-recommends iproute2
fi
managed_repo=false
if [[ -f /etc/apt/sources.list.d/pdns-auth-51.sources &&
      -f /etc/apt/sources.list.d/mariadb-foundation.sources ]] &&
   grep -q '^Suites: resolute-auth-51$' /etc/apt/sources.list.d/pdns-auth-51.sources &&
   grep -q '^URIs: https://deb.mariadb.org/12.3/ubuntu$' /etc/apt/sources.list.d/mariadb-foundation.sources; then
  managed_repo=true
fi
for pkg in pdns-server mariadb-server mysql-server; do
  if dpkg-query -W -f='${Status}' "$pkg" 2>/dev/null | grep -q 'install ok installed'; then
    [[ $managed_repo == true && $pkg != mysql-server ]] ||
      die "Existing $pkg installation is not from a resumable run of this installer."
  fi
done
if [[ $managed_repo == false ]]; then
  [[ ! -e /etc/powerdns/pdns.conf && ! -e /root/powerdns-credentials ]] ||
    die 'An existing PowerDNS configuration or credentials file would be overwritten.'
fi
while IFS= read -r source_file; do
  [[ -z $source_file ]] && continue
  if [[ $managed_repo != true ||
        ( $source_file != /etc/apt/sources.list.d/pdns-auth-51.sources &&
          $source_file != /etc/apt/sources.list.d/mariadb-foundation.sources ) ]]; then
    die "An existing DNS/database APT source needs manual review: $source_file"
  fi
done < <(grep -RlE '(repo\.powerdns\.com|deb\.mariadb\.org|mirror\.mariadb\.org|dlm\.mariadb\.com/repo)' \
          /etc/apt/sources.list /etc/apt/sources.list.d 2>/dev/null || true)
if [[ $managed_repo == true && -f /etc/powerdns/pdns.conf ]] &&
   ! grep -q '^# Generated by install-powerdns-ubuntu-26.04.sh$' /etc/powerdns/pdns.conf &&
   ! dpkg-query -S /etc/powerdns/pdns.conf >/dev/null 2>&1; then
  die 'Existing PowerDNS configuration is not owned by this installer or the package.'
fi

note 'Checking port 53...'
# Ubuntu systemd-resolved binds only its local stub; all other DNS listeners
# must be handled explicitly rather than silently stopping a production server.
listeners=$(ss -H -lntup '( sport = :53 )') || die 'Cannot inspect existing DNS listeners.'
while IFS= read -r listener; do
  [[ -z $listener || $listener == *systemd-resolve* ||
     ( $managed_repo == true && $listener == *'users:(("pdns_server"'* ) ]] ||
    die "Port 53 is in use: $listener"
done <<< "$listeners"
workdir=$(mktemp -d)
trap 'rm -rf -- "$workdir"' EXIT
note 'Installing repository prerequisites...'
apt-get update
apt-get install -y --no-install-recommends ca-certificates curl gnupg dnsutils openssl iproute2

install -d -m 0755 /etc/apt/keyrings
curl -fsSL --retry 3 --max-time 30 -o "$workdir/pdns.asc" \
  https://repo.powerdns.com/FD380FBB-pub.asc
curl -fsSL --retry 3 --max-time 30 -o "$workdir/mariadb.pgp" \
  https://mariadb.org/mariadb_release_signing_key.pgp
fingerprints() { gpg --batch --show-keys --with-colons --fingerprint "$1" 2>/dev/null | awk -F: '$1 == "fpr" {print $10}'; }
fingerprints "$workdir/pdns.asc" | grep -qx '9FAAA5577E8FCF62093D036C1B0C6205FD380FBB' ||
  die 'PowerDNS repository signing key fingerprint mismatch.'
fingerprints "$workdir/mariadb.pgp" | grep -qx '177F4010FE56CA3336300305F1656F24C74CD1D8' ||
  die 'MariaDB repository signing key fingerprint mismatch.'
install -m 0644 "$workdir/pdns.asc" /etc/apt/keyrings/pdns-auth-51.asc
install -m 0644 "$workdir/mariadb.pgp" /etc/apt/keyrings/mariadb-foundation.asc

cat > /etc/apt/sources.list.d/pdns-auth-51.sources <<'EOF'
Types: deb
URIs: https://repo.powerdns.com/ubuntu
Suites: resolute-auth-51
Components: main
Signed-By: /etc/apt/keyrings/pdns-auth-51.asc
EOF
cat > /etc/apt/preferences.d/pdns-auth-51 <<'EOF'
Package: pdns-*
Pin: origin repo.powerdns.com
Pin-Priority: 600
EOF
cat > /etc/apt/sources.list.d/mariadb-foundation.sources <<'EOF'
Types: deb
URIs: https://deb.mariadb.org/12.3/ubuntu
Suites: resolute
Components: main
Signed-By: /etc/apt/keyrings/mariadb-foundation.asc
EOF

note 'Installing MariaDB 12.3 and PowerDNS Authoritative 5.1...'
apt-get update
apt-get install -y --no-install-recommends mariadb-server pdns-server pdns-backend-mysql
[[ $(mariadb --version) == *'12.3.'* ]] || die 'MariaDB 12.3 was not installed.'
[[ $(pdns_server --version 2>&1) == *'5.1.'* ]] || die 'PowerDNS Authoritative 5.1 was not installed.'
install -d -m 0755 /etc/mysql/mariadb.conf.d
cat > /etc/mysql/mariadb.conf.d/99-powerdns-local.cnf <<'EOF'
[mariadbd]
bind-address=127.0.0.1
EOF
systemctl enable --now mariadb
systemctl restart mariadb
mariadb-admin ping --silent >/dev/null || die 'MariaDB is not responding.'

note 'Creating database and importing the package schema...'
database_exists=false
if [[ -n $(mariadb --batch --skip-column-names -e "SHOW DATABASES LIKE 'powerdns'") ]]; then
  [[ $managed_repo == true ]] || die 'The powerdns database already exists.'
  for table in domains records cryptokeys domainmetadata; do
    [[ -n $(mariadb --batch --skip-column-names powerdns -e "SHOW TABLES LIKE '$table'") ]] ||
      die "Existing powerdns database lacks $table; inspect before rerunning."
  done
  database_exists=true
fi
if [[ -f /root/powerdns-credentials ]]; then
  [[ $managed_repo == true ]] || die 'Existing credentials file needs manual review.'
  db_password=$(sed -n 's/^PowerDNS database password: //p' /root/powerdns-credentials)
  api_key=$(sed -n 's/^PowerDNS API key: //p' /root/powerdns-credentials)
  [[ $db_password =~ ^[[:xdigit:]]{64}$ && $api_key =~ ^[[:xdigit:]]{64}$ ]] ||
    die 'The existing credentials file is incomplete; inspect it before rerunning.'
else
  db_password=$(openssl rand -hex 32)
  api_key=$(openssl rand -hex 32)
fi
schema=''
while IFS= read -r path; do
  case "$path" in
    */schema.mysql.sql|*/schema.mysql.sql.gz) schema="$path"; break ;;
  esac
done < <(dpkg -L pdns-backend-mysql)
[[ -n $schema && -f $schema ]] || die 'The installed PowerDNS MySQL schema was not found.'
if [[ $database_exists == false ]]; then
  mariadb -e 'CREATE DATABASE powerdns'
  if [[ $schema == *.gz ]]; then
    gzip -dc -- "$schema" | mariadb powerdns
  else
    mariadb powerdns < "$schema"
  fi
fi
mariadb <<SQL
CREATE USER IF NOT EXISTS 'pdns'@'localhost' IDENTIFIED BY '$db_password';
ALTER USER 'pdns'@'localhost' IDENTIFIED BY '$db_password';
GRANT SELECT, INSERT, UPDATE, DELETE ON powerdns.* TO 'pdns'@'localhost';
SQL
mariadb --batch --skip-column-names powerdns -e 'SELECT COUNT(*) FROM cryptokeys' >/dev/null ||
  die 'DNSSEC schema verification failed.'
MYSQL_PWD="$db_password" mariadb --protocol=socket -u pdns powerdns \
  -e 'SELECT COUNT(*) FROM domains' >/dev/null || die 'PowerDNS database login failed.'

note 'Preparing DNS listeners and preserving the system resolver...'
if [[ $managed_repo == true ]] && systemctl is-active --quiet pdns; then
  systemctl stop pdns
fi
resolver_fallback=false
install -d -m 0755 /etc/systemd/resolved.conf.d
rm -f /etc/systemd/resolved.conf.d/powerdns-authoritative.conf
cat > /etc/systemd/resolved.conf.d/zz-powerdns-authoritative.conf <<'EOF'
[Resolve]
DNSStubListener=no
DNSStubListenerExtra=
EOF
if ! systemctl is-enabled --quiet systemd-resolved 2>/dev/null ||
   ! systemctl is-active --quiet systemd-resolved; then
  # A previously masked resolver is intentionally left off; a merely disabled
  # resolver is started so the upstream list stays available.
  if [[ $(systemctl is-enabled systemd-resolved 2>/dev/null || true) != masked ]]; then
    systemctl restart systemd-resolved
  fi
else
  systemctl restart systemd-resolved
fi
if [[ $(readlink -f /etc/resolv.conf 2>/dev/null || true) == /run/systemd/resolve/stub-resolv.conf ]] ||
   { [[ ! -L /etc/resolv.conf ]] && grep -qE '^nameserver[[:space:]]+127\.0\.0\.(53|54)([[:space:]]|$)' /etc/resolv.conf 2>/dev/null; }; then
  [[ -s /run/systemd/resolve/resolv.conf ]] || die 'systemd-resolved has no usable upstream resolver.'
  if [[ ! -e /etc/resolv.conf.before-powerdns ]]; then
    mv /etc/resolv.conf /etc/resolv.conf.before-powerdns
  else
    rm /etc/resolv.conf
  fi
  ln -s /run/systemd/resolve/resolv.conf /etc/resolv.conf
fi
listeners=$(ss -H -lntup '( sport = :53 )') || die 'Cannot verify port 53 is available.'
if [[ -n $listeners ]] && ! grep -v 'systemd-resolve' <<< "$listeners" | grep -q '[^[:space:]]'; then
  # Some hosts apply an additional resolver listener after our drop-in. For a
  # dedicated authoritative server, fall back to a persistent upstream file.
  [[ -s /run/systemd/resolve/resolv.conf ]] || die 'No upstream DNS list for resolver fallback.'
  cp /run/systemd/resolve/resolv.conf "$workdir/resolv.conf"
  grep -qE '^nameserver[[:space:]]+[^[:space:]]+' "$workdir/resolv.conf" ||
    die 'Resolver fallback has no upstream nameserver.'
  note 'Resolver still occupies port 53; switching the host to its existing upstream DNS list.'
  if [[ -L /etc/resolv.conf ]]; then
    rm /etc/resolv.conf
  else
    [[ ! -e /etc/resolv.conf.before-powerdns ]] &&
      cp -a /etc/resolv.conf /etc/resolv.conf.before-powerdns
  fi
  install -m 0644 "$workdir/resolv.conf" /etc/resolv.conf
  systemctl disable --now systemd-resolved
  systemctl mask --now systemd-resolved
  resolver_fallback=true
  if ! getent ahostsv4 repo.powerdns.com >/dev/null; then
    systemctl unmask systemd-resolved
    systemctl enable --now systemd-resolved
    die 'Upstream DNS check failed; systemd-resolved was restored.'
  fi
  listeners=$(ss -H -lntup '( sport = :53 )') || die 'Cannot verify port 53 after resolver fallback.'
fi
while IFS= read -r listener; do
  [[ -z $listener ]] || die "Port 53 is still in use: $listener"
done <<< "$listeners"

if [[ -f /root/powerdns-credentials && -f /etc/powerdns/pdns.conf ]] &&
   grep -q '^# Generated by install-powerdns-ubuntu-26.04.sh$' /etc/powerdns/pdns.conf; then
  note 'Keeping existing installer-managed PowerDNS configuration and API key.'
else
  make_api_hash
  local_addresses='0.0.0.0'
  [[ -e /proc/net/if_inet6 ]] && local_addresses+=',::'
  install -d -m 0755 /etc/powerdns
  cat > "$workdir/pdns.conf" <<EOF
# Generated by install-powerdns-ubuntu-26.04.sh
launch=gmysql
gmysql-socket=/run/mysqld/mysqld.sock
gmysql-dbname=powerdns
gmysql-user=pdns
gmysql-password=$db_password
gmysql-dnssec=yes

local-address=$local_addresses
local-port=53
primary=yes
secondary=no
allow-axfr-ips=

api=yes
api-key=$api_hash
webserver=yes
webserver-address=127.0.0.1
webserver-port=8081
webserver-allow-from=127.0.0.1
EOF
  install -o root -g pdns -m 0640 "$workdir/pdns.conf" /etc/powerdns/pdns.conf
fi
if [[ ! -f /root/powerdns-credentials ]]; then
  cat > "$workdir/powerdns-credentials" <<EOF
PowerDNS API URL: http://127.0.0.1:8081/api/v1
PowerDNS API key: $api_key
PowerDNS database: powerdns
PowerDNS database user: pdns
PowerDNS database password: $db_password
MariaDB administrator: sudo mariadb (local Unix socket authentication)
EOF
  install -o root -g root -m 0600 "$workdir/powerdns-credentials" /root/powerdns-credentials
fi

note 'Starting PowerDNS and verifying database, API, UDP, and TCP...'
systemctl enable --now pdns
systemctl restart pdns
verify_server

note 'PowerDNS is running. API: http://127.0.0.1:8081 (local only).'
note 'Credentials: /root/powerdns-credentials (root-readable only).'
if [[ $resolver_fallback == true ]]; then
  note 'systemd-resolved was masked; /etc/resolv.conf now holds a static copy of the current upstream DNS servers.'
  note 'Update /etc/resolv.conf if your provider changes those upstream addresses.'
fi
note 'No zones were created; add a primary zone and NS records before delegation.'
note 'DNSSEC is available per zone; signing a zone and publishing its DS are separate steps.'
